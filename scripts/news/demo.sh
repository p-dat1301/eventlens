#!/bin/sh
# Persistent local demo of the EventLens news web (docker/news-demo.compose.yaml,
# Compose project eventlens-news-demo). Data lives in the named volume
# eventlens-news-demo_news-demo-pg and survives stop/start/restart; nothing here
# runs `down -v`. Secrets are generated once into .private/news-demo.env.
#
#   scripts/news/demo.sh up            build (first time) + start, migrate
#   scripts/news/demo.sh import        handoff-import $NEWS_DEMO_HANDOFF_DIR/{articles.jsonl,manifest.json}
#                                      (host .venv, read-only, via the demo PostgreSQL port),
#                                      then `eventlens-rag rebuild` (chunks; fake embeddings)
#   scripts/news/demo.sh mode none     AI unavailable (default)
#   scripts/news/demo.sh mode fixture  explicit simulated AI (answers/summaries labelled fixture)
#   scripts/news/demo.sh stop|start|restart|status|logs [service]
#   scripts/news/demo.sh rebuild       rebuild images (after code changes) and restart
set -eu

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
ENV_FILE="$ROOT/.private/news-demo.env"
COMPOSE_FILE="$ROOT/docker/news-demo.compose.yaml"

secret() { python3 -c 'import secrets; print(secrets.token_urlsafe(48))'; }

ensure_env() {
    if [ ! -f "$ENV_FILE" ]; then
        mkdir -p "$(dirname "$ENV_FILE")"
        umask 077
        {
            echo "# Generated by scripts/news/demo.sh — local demo only, never commit."
            echo "NEWS_DEMO_DB_PASSWORD=$(secret)"
            echo "NEWS_DEMO_SERVICE_TOKEN=$(secret)"
            echo "NEWS_DEMO_CURSOR_SECRET=$(secret)"
            echo "NEWS_DEMO_AI_MODE=none"
            echo "NEWS_DEMO_HANDOFF_DIR=$HOME/Downloads"
        } >"$ENV_FILE"
        echo "created $ENV_FILE"
    fi
}

dc() { docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" "$@"; }

env_value() { sed -n "s/^$1=//p" "$ENV_FILE" | tail -n 1; }

set_mode() {
    case "$1" in
    none | fixture) ;;
    *)
        echo "mode must be none or fixture" >&2
        exit 2
        ;;
    esac
    tmp="$ENV_FILE.tmp"
    grep -v '^NEWS_DEMO_AI_MODE=' "$ENV_FILE" >"$tmp"
    echo "NEWS_DEMO_AI_MODE=$1" >>"$tmp"
    mv "$tmp" "$ENV_FILE"
    dc up --detach --wait rag-api rag-worker
    echo "AI mode: $1"
}

wait_http() {
    i=0
    until curl -fsS -o /dev/null "$1"; do
        i=$((i + 1))
        if [ "$i" -ge 60 ]; then
            echo "timeout waiting for $1" >&2
            return 1
        fi
        sleep 1
    done
}

WEB_PORT="${NEWS_DEMO_WEB_PORT:-18080}"

urls() {
    echo "web (production Nginx): http://127.0.0.1:$WEB_PORT/news"
    echo "AI mode: $(env_value NEWS_DEMO_AI_MODE)"
}

ensure_env
cmd="${1:-status}"
case "$cmd" in
up)
    dc build
    dc up --detach --wait postgres
    dc run --rm tools eventlens-rag migrate
    dc up --detach rag-api crud-api rag-worker web
    wait_http "http://127.0.0.1:$WEB_PORT/api/v1/topics"
    urls
    ;;
rebuild)
    dc build
    dc up --detach --wait postgres
    dc run --rm tools eventlens-rag migrate
    dc up --detach --force-recreate rag-api crud-api rag-worker web
    urls
    ;;
import)
    dir=$(env_value NEWS_DEMO_HANDOFF_DIR)
    pass=$(env_value NEWS_DEMO_DB_PASSWORD)
    # The importer refuses any database whose name does not end in _eval.
    EVENTLENS_RAG_EVAL_DATABASE_URL="postgresql://eventlens_demo:$pass@127.0.0.1:${NEWS_DEMO_PG_PORT:-55442}/eventlens_news_eval" \
        "$ROOT/.venv/bin/eventlens-rag" handoff-import \
        --articles "$dir/articles.jsonl" --manifest "$dir/manifest.json"
    # Retrieval chunks for chat: fake embeddings (vector branch meaningless), lexical real.
    dc run --rm tools eventlens-rag rebuild
    ;;
mode) set_mode "${2:?none|fixture}" ;;
start)
    dc up --detach rag-api crud-api rag-worker web
    urls
    ;;
stop) dc stop ;;
restart)
    dc restart
    urls
    ;;
status)
    dc ps
    urls
    ;;
logs)
    shift
    dc logs --tail 100 "$@"
    ;;
*)
    echo "usage: $0 up|import|mode none|fixture|start|stop|restart|status|logs|rebuild" >&2
    exit 2
    ;;
esac
